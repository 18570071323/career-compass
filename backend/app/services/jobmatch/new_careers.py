def search_careers(q: str = "", group: str = "", major: str = "") -> list[dict]:
    """筛选 + 按专业适配排序（适配专业关键词命中越多的排前，不参与分数）。"""
    items = NEW_CAREERS
    if q:
        ql = q.lower()
        items = [
            c
            for c in items
            if ql in c["name"].lower()
            or ql in (c.get("summary") or "").lower()
            or ql in " ".join(c.get("skills") or []).lower()
        ]
    if group:
        items = [c for c in items if c["group"] == group]

    def _rel(c: dict) -> int:
        if not major:
            return 0
        return sum(1 for kw in c.get("fit_majors") or [] if kw and kw.lower() in major.lower())

    items = sorted(items, key=lambda c: (-_rel(c), c["name"]))
    return items
